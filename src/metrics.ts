/** Width of `text` in em at the given letter-spacing (in em). */
export function textWidth(text: string, tracking: number) {
  let width = 0;
  for (const char of text) width += (widths[char] ?? 0.56) + tracking;
  return Math.round(width * 1000) / 1000;
}
